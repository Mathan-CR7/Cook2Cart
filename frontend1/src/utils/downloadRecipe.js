/**
 * Downloads recipe data as a plain-text (.txt) file.
 */
export function downloadAsTxt(recipe) {
  const { title, ingredients = [], instructions = [] } = recipe;

  const lines = [];

  lines.push('╔══════════════════════════════════════════╗');
  lines.push(`  ${(title || 'My Recipe').toUpperCase()}`);
  lines.push('╚══════════════════════════════════════════╝');
  lines.push('');
  lines.push('INGREDIENTS');
  lines.push('──────────────────────────────────────────');
  if (ingredients.length > 0) {
    ingredients.forEach((ing, i) => {
      const qty   = ing.recipeQuantity ?? ing.quantity ?? '';
      const unit  = ing.recipeUnit    ?? ing.unit      ?? 'pcs';
      const name  = ing.name || '';
      lines.push(`  ${i + 1}. ${name.padEnd(22)} ${qty} ${unit}`);
    });
  } else {
    lines.push('  No ingredients listed.');
  }

  if (instructions.length > 0) {
    lines.push('');
    lines.push('COOKING INSTRUCTIONS');
    lines.push('──────────────────────────────────────────');
    instructions.forEach((step, i) => {
      lines.push(`  Step ${String(i + 1).padStart(2, '0')}: ${step}`);
      lines.push('');
    });
  }

  lines.push('──────────────────────────────────────────');
  lines.push('  Generated by Cook2Cart');
  lines.push('');

  const blob    = new Blob([lines.join('\n')], { type: 'text/plain;charset=utf-8' });
  const url     = URL.createObjectURL(blob);
  const anchor  = document.createElement('a');
  anchor.href   = url;
  anchor.download = `${(title || 'recipe').replace(/[^a-z0-9]/gi, '_').toLowerCase()}.txt`;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

/**
 * Opens a hidden print window with a nicely formatted recipe card and triggers the browser print dialog.
 * The user can choose "Save as PDF" from there.
 */
export function downloadAsPdf(recipe) {
  const { title, ingredients = [], instructions = [] } = recipe;

  const safeTitle = title || 'My Recipe';

  const ingredientRows = ingredients.length > 0
    ? ingredients.map((ing, i) => {
        const qty  = ing.recipeQuantity ?? ing.quantity ?? '';
        const unit = ing.recipeUnit    ?? ing.unit      ?? 'pcs';
        const name = ing.name || '';
        return `
          <tr style="border-bottom:1px solid #f3f4f6;">
            <td style="padding:10px 12px;color:#6b7280;font-size:13px;">${i + 1}</td>
            <td style="padding:10px 12px;font-weight:600;color:#111827;font-size:14px;">${name}</td>
            <td style="padding:10px 12px;color:#f97316;font-weight:700;font-size:14px;text-align:right;">${qty} ${unit}</td>
          </tr>`;
      }).join('')
    : `<tr><td colspan="3" style="padding:16px;color:#9ca3af;text-align:center;">No ingredients listed</td></tr>`;

  const instructionSteps = instructions.length > 0
    ? instructions.map((step, i) => `
        <div style="display:flex;gap:12px;margin-bottom:14px;align-items:flex-start;">
          <div style="min-width:28px;height:28px;border-radius:50%;background:linear-gradient(135deg,#f97316,#ef4444);color:#fff;font-size:11px;font-weight:700;display:flex;align-items:center;justify-content:center;flex-shrink:0;">
            ${String(i + 1).padStart(2, '0')}
          </div>
          <p style="margin:0;color:#374151;font-size:14px;line-height:1.6;">${step}</p>
        </div>`).join('')
    : '';

  const html = `
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>${safeTitle} — Cook2Cart</title>
  <style>
    @import url('https://fonts.googleapis.com/css2?family=Inter:wght@400;600;700;800&display=swap');
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body { font-family: 'Inter', sans-serif; background: #fff; color: #111827; padding: 40px; max-width: 680px; margin: 0 auto; }
    @media print {
      body { padding: 20px; }
      button { display: none !important; }
    }
  </style>
</head>
<body>

  <!-- Header -->
  <div style="background:linear-gradient(135deg,#f97316,#ef4444);border-radius:20px;padding:32px 28px;margin-bottom:28px;color:#fff;">
    <div style="font-size:11px;font-weight:700;text-transform:uppercase;letter-spacing:2px;opacity:0.8;margin-bottom:8px;">Recipe</div>
    <h1 style="font-size:26px;font-weight:800;line-height:1.2;">${safeTitle}</h1>
    <div style="margin-top:14px;display:flex;gap:16px;opacity:0.85;font-size:13px;">
      <span>🥗 ${ingredients.length} ingredients</span>
      ${instructions.length > 0 ? `<span>📋 ${instructions.length} steps</span>` : ''}
      <span>🍳 Cook2Cart</span>
    </div>
  </div>

  <!-- Ingredients -->
  <div style="margin-bottom:28px;">
    <h2 style="font-size:16px;font-weight:700;color:#111827;margin-bottom:14px;display:flex;align-items:center;gap:8px;">
      <span style="display:inline-block;width:4px;height:20px;background:linear-gradient(135deg,#f97316,#ef4444);border-radius:4px;"></span>
      Ingredients
    </h2>
    <table style="width:100%;border-collapse:collapse;background:#fff;border-radius:14px;overflow:hidden;box-shadow:0 1px 4px rgba(0,0,0,0.07);">
      <thead>
        <tr style="background:#fef3f2;">
          <th style="padding:10px 12px;text-align:left;font-size:11px;color:#9ca3af;font-weight:600;text-transform:uppercase;letter-spacing:1px;width:36px;">#</th>
          <th style="padding:10px 12px;text-align:left;font-size:11px;color:#9ca3af;font-weight:600;text-transform:uppercase;letter-spacing:1px;">Ingredient</th>
          <th style="padding:10px 12px;text-align:right;font-size:11px;color:#9ca3af;font-weight:600;text-transform:uppercase;letter-spacing:1px;">Quantity</th>
        </tr>
      </thead>
      <tbody>${ingredientRows}</tbody>
    </table>
  </div>

  ${instructions.length > 0 ? `
  <!-- Instructions -->
  <div style="margin-bottom:28px;">
    <h2 style="font-size:16px;font-weight:700;color:#111827;margin-bottom:14px;display:flex;align-items:center;gap:8px;">
      <span style="display:inline-block;width:4px;height:20px;background:linear-gradient(135deg,#f97316,#ef4444);border-radius:4px;"></span>
      Cooking Instructions
    </h2>
    <div style="background:#fffbf9;border:1px solid #fde8d8;border-radius:14px;padding:20px;">
      ${instructionSteps}
    </div>
  </div>` : ''}

  <!-- Footer -->
  <div style="text-align:center;padding-top:20px;border-top:1px solid #f3f4f6;color:#9ca3af;font-size:12px;">
    Generated by Cook2Cart • cook2cart.app
  </div>

</body>
</html>`;

  const printWindow = window.open('', '_blank', 'width=760,height=900');
  if (!printWindow) {
    alert('Please allow pop-ups for this site to use the PDF download.');
    return;
  }
  printWindow.document.write(html);
  printWindow.document.close();
  printWindow.focus();
  // Small delay so fonts/styles load before the print dialog
  setTimeout(() => {
    printWindow.print();
  }, 600);
}
